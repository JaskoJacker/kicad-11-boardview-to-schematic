#!/usr/bin/env python3
"""
net_check.py — MODULE (not launched on its own)

CHECK logic on the open KiCad schematic: given a set of pins that should be connected to the
same net (according to the boardview), it verifies whether they really are, whether they ended up
on the right net and whether the net has the correct name. It is a separate module precisely so
that it can be reused as it is by a future GUI: it knows nothing about
threads, queues or menus — it just receives an already prepared `sch` object
(kipy.schematic.Schematic). Whoever calls it (the interactive session: inside a KiCadWorker job)
takes care of how to get there safely.

CHECK PRINCIPLE (decided with the technician): since in the interactive workflow it is the
technician who chooses which components of the net to place (not all at once), `check` concerns
ONLY the pins actually placed/highlighted, never the whole boardview net — it is not an error if some members have not
been inserted yet.

`audit` is the complement (added 2026-10-18 after a wrong net went unnoticed): it looks at EVERY
pin of EVERY placed component, highlighted or not, and finds what `check` cannot see — a wire that
joins pins of different boardview nets (a short), and a KiCad net whose name is not the name of the
boardview net its pins belong to, even if those pins were confirmed earlier.
"""

from kipy.geometry import Vector2
from kipy.schematic_types import BaseLabel, GlobalLabel, HierarchicalLabel, LocalLabel

NET_LABEL_TYPES = (LocalLabel, GlobalLabel, HierarchicalLabel)   # the labels that name a net
TOLERANCE_NM = 1000  # 1 micron: for coordinate comparisons (internal rounding)


def near(a: Vector2, b: Vector2, tolerance_nm: int = TOLERANCE_NM) -> bool:
    return abs(a.x - b.x) <= tolerance_nm and abs(a.y - b.y) <= tolerance_nm


def kicad_net_at_position(sch, position: Vector2):
    """Name of the KiCad net whose wire touches `position`, or None if no
    wire or label passes there (unconnected pin). Comparison by coincidence of
    coordinates: the same mechanism KiCad itself uses to compute
    connectivity (it is not a saved explicit reference, it is always a geometric
    recomputation)."""
    return net_from_map(net_position_map(sch), position)


def _nets_with_points(sch):
    """For each KiCad net: (name, ends of all its wires and the anchors of its labels). It is a generator:
    the calls to KiCad (one get_items_by_id per net) happen only as needed,
    so whoever looks for ONE pin stops at the first net that contains it."""
    for net in sch.get_netlist():
        ids = [item for sheet in net.sheets for item in sheet.items]
        if not ids:
            continue
        try:
            items = sch.get_items_by_id(ids)
        except Exception:
            continue
        points = []
        for item in items:
            for attribute in ("start", "end"):
                p = getattr(item, attribute, None)
                if p is not None:
                    points.append(p)
            if isinstance(item, BaseLabel):
                points.append(item.position)   # a label connects at its anchor, wire or no wire
        yield net.name, points


def net_labels(sch) -> list:
    """The labels of the schematic that name a net (a directive label does not)."""
    return [label for label in sch.get_labels() if isinstance(label, NET_LABEL_TYPES)]


def net_position_map(sch, labels: list | None = None) -> list:
    """Like kicad_net_at_position but for MANY pins: builds only once the list
    (net name, wire ends and label anchors) to be queried with net_from_map(), instead of
    re-reading everything from KiCad for each pin (needed to resume a session).

    A net can be NAMED DIRECTLY ON A PIN: a label whose anchor sits on the pin and no wire at all
    (the technician cannot draw a net that closes on no other component yet). Whether KiCad's
    netlist lists such a net or not, it is added here from the labels (`labels`: net_labels(sch) if
    the caller already has it): a label touching no known net makes a net of its own, and labels
    with the same name are one net, as in KiCad."""
    mapping = list(_nets_with_points(sch))
    for label in (net_labels(sch) if labels is None else labels):
        position = label.position
        if any(near(p, position) for _name, points in mapping for p in points):
            continue
        name = label.text.value
        same_name = next((points for n, points in mapping if n.lstrip("/") == name.lstrip("/")), None)
        if same_name is None:
            mapping.append((name, [position]))
        else:
            same_name.append(position)
    return mapping


def net_from_map(mapping: list, position: Vector2):
    for name, points in mapping:
        if any(near(p, position) for p in points):
            return name
    return None


def is_autogenerated_name(kicad_name: str) -> bool:
    """KiCad generates by itself names like 'Net-(R1-Pad1)' or 'unconnected-(R2-Pad2)'
    when no label has been assigned by the technician."""
    return kicad_name.startswith("Net-(") or kicad_name.startswith("unconnected-(")


class CheckResult:
    """Outcome of a check, designed to be used both by a command-line
    interface (prints the messages) and in the future by a GUI (reads the
    structured fields and shows them as it prefers, without having to redo the
    calculations). It contains no logic, only data + the ready-made messages
    in English (convenient for the CLI, not binding for the GUI)."""

    def __init__(self):
        self.confirmed_ok_pins: list[tuple[str, str]] = []
        self.unconnected_pins: list[tuple[str, str]] = []
        # (refdes, expected_pin, found_connected_pin, net_name)
        self.wrong_pins: list[tuple[str, str, str, str]] = []
        self.kicad_net_name: str | None = None  # None if no pin connected or mixed nets
        self.mixed_nets: dict[tuple[str, str], str] = {}  # filled only if the nets do not coincide
        self.messages: list[str] = []
        # complete: at least two pins, all wired, all on one KiCad net, no wrong pin -> the net is "finished"
        self.complete = False
        self.unnamed = False        # the single KiCad net has an auto-generated name

    def ok(self) -> bool:
        """All fine: no problem detected on ANY of the checked pins."""
        return (
            not self.unconnected_pins
            and not self.wrong_pins
            and not self.mixed_nets
            and self.kicad_net_name is not None
        )


def check(sch, absolute_pin_fn, net_name_boardview: str,
          pins_to_check: list[tuple[str, str]],
          other_pins_fn, net_map: list | None = None) -> CheckResult:
    """Pure check function (no printing, no access to Session):
    receives `sch` (already prepared) and `absolute_pin_fn(refdes, pin) -> Vector2`
    (typically Session.absolute_pin_position, passed as a callback so as not to create
    a direct dependency on that class), and returns a CheckResult
    with all the details — the caller decides how to present them (printing
    on screen for the CLI, graphic highlighting for a future GUI).

    `other_pins_fn(refdes, pin) -> list[str]`: the other pins of the same
    component, to understand whether the technician connected the wrong pin. An expected
    pin that is not connected can mean two things: either it has not been connected yet, or
    the technician connected ANOTHER pin of the same component. "Wrong pin" is reported only
    if that other pin is on the net expected by the boardview (net with the right name) or on
    the same KiCad net as the other pins of the group. Another pin connected to ANY net is
    instead normal: with the multi-net flow a component is often already
    connected on one side and the pin to check is the next one (corrected 2026-10-03: the rule
    "it is enough that the other pin is connected" gave a false alarm on R3239.2).

    `net_map` (optional): the result of net_position_map(sch), when the caller has already
    computed it for several checks; otherwise it is computed here, once."""
    r = CheckResult()
    if net_map is None:
        net_map = net_position_map(sch)

    found_nets: dict[tuple[str, str], str] = {}
    not_found: list[tuple[str, str]] = []
    for (refdes, pin) in pins_to_check:
        kicad_net = net_from_map(net_map, absolute_pin_fn(refdes, pin))
        if kicad_net is not None:
            found_nets[(refdes, pin)] = kicad_net
        else:
            not_found.append((refdes, pin))

    group_nets = set(found_nets.values())
    for (refdes, pin) in not_found:
        candidates = other_pins_fn(refdes, pin)
        suspect = None
        for other in candidates:
            other_net_name = net_from_map(net_map, absolute_pin_fn(refdes, other))
            if other_net_name is None:
                continue
            if (other_net_name.lstrip("/") == net_name_boardview
                    or other_net_name in group_nets):
                suspect = (other, other_net_name)
                break

        if suspect is not None:
            other, other_net_name = suspect
            r.wrong_pins.append((refdes, pin, other, other_net_name))
            r.messages.append(
                f"[!] WRONG PIN: on {refdes} pin {pin} was expected to be connected "
                f"(the highlighted one), but pin {other} is connected instead "
                f"(on net '{other_net_name}')."
            )
        else:
            r.unconnected_pins.append((refdes, pin))

    if r.unconnected_pins:
        listing = ", ".join(f"{x}.{y}" for x, y in r.unconnected_pins)
        r.messages.append(f"[!] NOT CONNECTED (no wire touches the pin): {listing}")

    distinct_names = set(found_nets.values())
    if len(distinct_names) > 1:
        r.mixed_nets = dict(found_nets)
        r.messages.append(
            "[!] WARNING: the connected pins are NOT all on the same KiCad net "
            "(probably a wrong pin connected by the technician):"
        )
        for (x, y), kicad_net in found_nets.items():
            r.messages.append(f"      {x}.{y} -> '{kicad_net}'")
    elif len(distinct_names) == 1:
        kicad_name = next(iter(distinct_names))
        r.kicad_net_name = kicad_name
        r.unnamed = is_autogenerated_name(kicad_name)
        clean_name = kicad_name.lstrip("/")
        if is_autogenerated_name(kicad_name):
            r.messages.append(
                f"[!] Net without a name assigned by the technician (KiCad calls it "
                f"'{kicad_name}'). Name expected from the boardview: '{net_name_boardview}'."
            )
        elif clean_name != net_name_boardview:
            r.messages.append(
                f"[!] Net name differs from the boardview one: "
                f"KiCad='{kicad_name}', boardview='{net_name_boardview}'."
            )
        else:
            r.messages.append(f"[OK] Net named correctly: '{kicad_name}'.")
            r.confirmed_ok_pins = list(found_nets.keys())
    else:
        r.messages.append("(no connected pin to check)")

    r.complete = (len(pins_to_check) >= 2 and not r.unconnected_pins and not r.wrong_pins
                  and not r.mixed_nets and r.kicad_net_name is not None)
    return r


class AuditResult:
    """Outcome of `audit`: structured findings plus ready-made messages."""

    def __init__(self):
        # (kicad net name, {boardview net: ["U1.3", ...]}) — pins of several boardview nets on one net
        self.shorts: list[tuple[str, dict[str, list[str]]]] = []
        # (kicad net name, boardview net, pins) — named by the technician, but with another name
        self.wrong_names: list[tuple[str, str, list[str]]] = []
        # (auto-generated kicad name, boardview net, pins) — wired but not named
        self.unnamed: list[tuple[str, str, list[str]]] = []
        # (kicad net name, pins) — a net attached to a single pin: it joins nothing
        self.dangling: list[tuple[str, list[str]]] = []
        self.connected_pins = 0
        self.messages: list[str] = []

    def ok(self) -> bool:
        return not (self.shorts or self.wrong_names or self.unnamed or self.dangling)


def audit(sch, placed_pins: list[tuple[str, str, str]], absolute_pin_fn,
          net_map: list | None = None, all_pin_points: list | None = None,
          label_points: list | None = None) -> AuditResult:
    """Checks every wired pin of the placed components against the boardview.

    `placed_pins`: [(refdes, pin, boardview net)] for ALL the pins of the placed components.
    `absolute_pin_fn(refdes, pin) -> Vector2`: where the pin is on the schematic.
    `net_map`: net_position_map(sch) if the caller already has it.
    `all_pin_points`: the positions of the pins of EVERY symbol on the sheet (ours or not). With it,
    a KiCad net that touches only one pin is reported as dangling; without it that check is skipped.
    `label_points`: the anchors of the net labels; a single-pin net that is only a label sitting right ON
    the pin (no wire) is not dangling, it is a net named directly on the pin (to be joined to the rest
    later).
    The KiCad net of a pin is the one whose wire touches it (as in `check`). Pins no wire touches
    are ignored: they are not wrong, just not connected yet."""
    result = AuditResult()
    mapping = net_map if net_map is not None else net_position_map(sch)
    by_kicad: dict[str, dict[str, list[str]]] = {}
    for refdes, pin, boardview_net in placed_pins:
        if boardview_net is None:
            continue
        kicad_net = net_from_map(mapping, absolute_pin_fn(refdes, pin))
        if kicad_net is None:
            continue
        result.connected_pins += 1
        by_kicad.setdefault(kicad_net, {}).setdefault(boardview_net, []).append(f"{refdes}.{pin}")

    if all_pin_points is not None:
        wire_points = dict(mapping)
        for kicad_net, groups in by_kicad.items():
            touched = []
            for point in all_pin_points:
                if any(near(point, w) for w in wire_points[kicad_net]) and \
                        not any(near(point, t) for t in touched):
                    touched.append(point)
            # named on the pin: the net is made of labels sitting on pins and NOTHING else (a wire that
            # starts on the pin and goes nowhere is still a dangling net, label or not)
            named_on_pin = all(any(near(w, l) for l in (label_points or ())) for w in wire_points[kicad_net])
            if len(touched) < 2 and not named_on_pin:
                pins = [pin for pins in groups.values() for pin in pins]
                result.dangling.append((kicad_net, pins))
                result.messages.append(
                    f"[!] DANGLING NET: KiCad net '{kicad_net}' is attached only to {', '.join(pins)}: "
                    f"a net must join at least two pins.")

    dangling_nets = {n for n, _p in result.dangling}
    for kicad_net, groups in by_kicad.items():
        if kicad_net in dangling_nets:
            continue
        if len(groups) > 1:
            result.shorts.append((kicad_net, groups))
            parts = " | ".join(f"{net}: {', '.join(pins)}" for net, pins in groups.items())
            result.messages.append(
                f"[!] SHORT: KiCad net '{kicad_net}' joins pins of different boardview nets -> {parts}")
            continue
        (boardview_net, pins), = groups.items()
        if is_autogenerated_name(kicad_net):
            result.unnamed.append((kicad_net, boardview_net, pins))
            result.messages.append(
                f"[!] UNNAMED NET: {', '.join(pins)} are wired together (KiCad calls it '{kicad_net}') "
                f"but belong to boardview net '{boardview_net}': label it '{boardview_net}'.")
        elif kicad_net.lstrip("/") != boardview_net:
            result.wrong_names.append((kicad_net, boardview_net, pins))
            result.messages.append(
                f"[!] WRONG NET NAME: {', '.join(pins)} belong to boardview net '{boardview_net}' "
                f"but the KiCad net is named '{kicad_net}'.")
    return result


def net_items(sch, kicad_net_name: str) -> list:
    """The wires, labels... of one KiCad net as KiCad reports them (pins are not included: KiCad
    does not return them as separate items)."""
    for net in sch.get_netlist():
        if net.name == kicad_net_name:
            ids = [item for sheet in net.sheets for item in sheet.items]
            found = list(sch.get_items_by_id(ids)) if ids else []
            break
    else:
        found = []
    # a net named only by labels on pins may be missing from KiCad's netlist: take its labels from here
    known = {item.id.value for item in found}
    wanted = kicad_net_name.lstrip("/")
    found += [label for label in net_labels(sch)
              if label.text.value.lstrip("/") == wanted and label.id.value not in known]
    return found
